export function isFormUrl(value, expected) {
  try {
    const url = new URL(value);
    const target = new URL(expected);
    return url.origin === target.origin &&
      url.pathname.replace(/\/+$/, "") === target.pathname.replace(/\/+$/, "");
  } catch {
    return false;
  }
}
